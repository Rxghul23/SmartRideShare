CREATE DATABASE IF NOT EXISTS smartride CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE smartride;
CREATE TABLE IF NOT EXISTS users (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, name VARCHAR(100) NOT NULL, email VARCHAR(190) UNIQUE NOT NULL,
 password_hash VARCHAR(300) NOT NULL, department VARCHAR(100) NOT NULL DEFAULT 'General',
 role ENUM('EMPLOYEE','ADMIN') NOT NULL DEFAULT 'EMPLOYEE', active BOOLEAN NOT NULL DEFAULT TRUE,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS rides (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, driver_id BIGINT NOT NULL, origin VARCHAR(120) NOT NULL, destination VARCHAR(120) NOT NULL,
 origin_lat DOUBLE NOT NULL, origin_lng DOUBLE NOT NULL, dest_lat DOUBLE NOT NULL, dest_lng DOUBLE NOT NULL,
 departure DATETIME NOT NULL, seats INT NOT NULL, available_seats INT NOT NULL, price DECIMAL(10,2) NOT NULL,
 distance_km DOUBLE NOT NULL, preference ENUM('quiet','chatty','any') NOT NULL DEFAULT 'any',
 status ENUM('OPEN','COMPLETED','CANCELLED') NOT NULL DEFAULT 'OPEN', created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(driver_id) REFERENCES users(id), CHECK(seats BETWEEN 1 AND 7), CHECK(available_seats BETWEEN 0 AND seats), CHECK(price>=0), CHECK(distance_km>0), INDEX(departure,status)
);
CREATE TABLE IF NOT EXISTS ride_requests (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, user_id BIGINT NOT NULL, origin VARCHAR(120) NOT NULL, destination VARCHAR(120) NOT NULL,
 origin_lat DOUBLE NOT NULL, origin_lng DOUBLE NOT NULL, dest_lat DOUBLE NOT NULL, dest_lng DOUBLE NOT NULL,
 departure DATETIME NOT NULL, tolerance INT NOT NULL DEFAULT 45, preference ENUM('quiet','chatty','any') NOT NULL DEFAULT 'any',
 status ENUM('OPEN','BOOKED','CANCELLED') NOT NULL DEFAULT 'OPEN', created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(user_id) REFERENCES users(id), INDEX(departure)
);
CREATE TABLE IF NOT EXISTS bookings (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, ride_id BIGINT NOT NULL, passenger_id BIGINT NOT NULL, request_id BIGINT NULL,
 status ENUM('CONFIRMED','CANCELLED','COMPLETED') NOT NULL DEFAULT 'CONFIRMED', created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(ride_id) REFERENCES rides(id), FOREIGN KEY(passenger_id) REFERENCES users(id), FOREIGN KEY(request_id) REFERENCES ride_requests(id),
 UNIQUE(ride_id,passenger_id)
);
CREATE TABLE IF NOT EXISTS match_history (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, request_id BIGINT NOT NULL, ride_id BIGINT NOT NULL, score DOUBLE NOT NULL,
 features JSON NOT NULL, model_version VARCHAR(100) NOT NULL, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(request_id) REFERENCES ride_requests(id), FOREIGN KEY(ride_id) REFERENCES rides(id), UNIQUE(request_id,ride_id)
);
CREATE TABLE IF NOT EXISTS feedback (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, booking_id BIGINT NOT NULL UNIQUE, rating INT NOT NULL, comment VARCHAR(500) NOT NULL DEFAULT '',
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP, FOREIGN KEY(booking_id) REFERENCES bookings(id), CHECK(rating BETWEEN 1 AND 5)
);
CREATE TABLE IF NOT EXISTS settings (id INT PRIMARY KEY, max_route_km DOUBLE NOT NULL DEFAULT 5, co2_kg_per_km DOUBLE NOT NULL DEFAULT 0.12, solo_cost_per_km DOUBLE NOT NULL DEFAULT 8);
INSERT IGNORE INTO settings(id) VALUES(1);
CREATE TABLE IF NOT EXISTS audit_log (id BIGINT PRIMARY KEY AUTO_INCREMENT, user_id BIGINT NULL, action VARCHAR(120) NOT NULL, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP);
